// ─── COMPONENTE ────────────────────────────────────────────

export function DashboardSidebar() {
  const pathname = usePathname();
  const router = useRouter();
  const user = useAuthStore((state) => state.user);
  const logout = useAuthStore((state) => state.logout);

  const userRole: UserRole = user?.role ?? "client";

  const visibleItems = NAV_ROUTES.filter((item) =>
    (item.roles as readonly UserRole[]).includes(userRole)
  );

  const handleLogout = async () => {
    await logout();
    router.push("/login");
  };

  return (
    <div className="flex flex-col h-full">
      <div className="flex items-center h-16 px-6 border-b border-gray-200">
        <h1 className="text-lg font-bold text-gray-900 truncate">{APP.NAME}</h1>
      </div>

      <nav className="flex-1 overflow-y-auto px-3 py-4 space-y-1">
        {visibleItems.map((item) => {
          const isActive =
            pathname === item.href ||
            (item.href !== "/dashboard" && pathname.startsWith(item.href));

          return (
            <button key={item.href} onClick={() => router.push(item.href)}
              className={`group flex items-center w-full gap-3 rounded-md px-3 py-2 text-sm font-medium transition-colors ${
                isActive ? "bg-indigo-50 text-indigo-700" : "text-gray-700 hover:bg-gray-50 hover:text-gray-900"
              }`}>
              <span className={isActive ? "text-indigo-600" : "text-gray-400 group-hover:text-gray-500"}>
                {ICONS[item.icon] ?? null}
              </span>
              {item.label}
            </button>
          );
        })}
      </nav>

      <div className="border-t border-gray-200 px-4 py-4">
        <div className="flex items-center gap-3">
          <div className="flex-shrink-0 h-9 w-9 rounded-full bg-indigo-100 flex items-center justify-center">
            <span className="text-sm font-medium text-indigo-700">
              {user?.full_name?.charAt(0).toUpperCase() ?? "U"}
            </span>
          </div>
          <div className="flex-1 min-w-0">
            <p className="text-sm font-medium text-gray-900 truncate">{user?.full_name ?? "Usuario"}</p>
            <p className="text-xs text-gray-500 truncate capitalize">{user?.role ?? ""}</p>
          </div>
          <button onClick={handleLogout} title="Cerrar sesión"
            className="flex-shrink-0 p-1.5 rounded-md text-gray-400 hover:text-gray-600 hover:bg-gray-100 transition-colors">
            <svg className="h-5 w-5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
              <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15m3 0l3-3m0 0l-3-3m3 3H9" />
            </svg>
          </button>
        </div>
      </div>
    </div>
  );
}

export default DashboardSidebar;